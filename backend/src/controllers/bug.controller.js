const axios = require('axios');

/**
 * POST /api/bugs/github
 * Creates a GitHub Issue from a failed payload result
 */
exports.createGitHubIssue = async (req, res, next) => {
  try {
    const { results, reportName, reportUrl } = req.body;

    const token = process.env.GITHUB_TOKEN;
    const owner = process.env.GITHUB_OWNER;
    const repo  = process.env.GITHUB_REPO;

    if (!token || !owner || !repo) {
      return res.status(400).json({
        error: 'GitHub not configured. Set GITHUB_TOKEN, GITHUB_OWNER, GITHUB_REPO in .env',
      });
    }

    if (!results || !results.length) {
      return res.status(400).json({ error: 'No results provided' });
    }

    const created = [];

    for (const result of results) {
      const statusLabel = result.passed ? '✅ PASS' : '❌ FAIL';
      const body = `
## API Test Failure Report

**Report:** ${reportName || 'Unknown'}
**Case:** ${result.payloadName}
**Status:** ${statusLabel} — HTTP ${result.statusCode} ${result.statusText || ''}
**Latency:** ${result.latencyMs}ms
${reportUrl ? `**Report URL:** ${reportUrl}` : ''}

---

### Request Payload Sent

\`\`\`json
${JSON.stringify(result.payloadBody, null, 2)}
\`\`\`

### Response Received

\`\`\`json
${result.error ? result.error : JSON.stringify(result.response, null, 2)}
\`\`\`

---
*Auto-generated by API Flow Tester*
`.trim();

      const response = await axios.post(
        `https://api.github.com/repos/${owner}/${repo}/issues`,
        {
          title: `[API Failure] ${result.payloadName} — HTTP ${result.statusCode}`,
          body,
          labels: ['bug', 'api-test-failure'],
        },
        {
          headers: {
            Authorization: `Bearer ${token}`,
            Accept: 'application/vnd.github+json',
            'X-GitHub-Api-Version': '2022-11-28',
          },
        }
      );

      created.push({
        issueNumber: response.data.number,
        issueUrl: response.data.html_url,
        title: response.data.title,
        payloadName: result.payloadName,
      });
    }

    res.json({ created, count: created.length });
  } catch (err) {
    if (err.response?.data) {
      return res.status(err.response.status || 500).json({
        error: err.response.data.message || 'GitHub API error',
        details: err.response.data,
      });
    }
    next(err);
  }
};

/**
 * POST /api/bugs/jira
 * Creates a Jira issue from a failed payload result
 */
exports.createJiraIssue = async (req, res, next) => {
  try {
    const { results, reportName, reportUrl } = req.body;

    const host     = process.env.JIRA_HOST;       // e.g. yourcompany.atlassian.net
    const email    = process.env.JIRA_EMAIL;
    const apiToken = process.env.JIRA_API_TOKEN;
    const project  = process.env.JIRA_PROJECT_KEY; // e.g. DEV

    if (!host || !email || !apiToken || !project) {
      return res.status(400).json({
        error: 'Jira not configured. Set JIRA_HOST, JIRA_EMAIL, JIRA_API_TOKEN, JIRA_PROJECT_KEY in .env',
      });
    }

    if (!results || !results.length) {
      return res.status(400).json({ error: 'No results provided' });
    }

    const auth = Buffer.from(`${email}:${apiToken}`).toString('base64');
    const created = [];

    for (const result of results) {
      const description = {
        type: 'doc',
        version: 1,
        content: [
          {
            type: 'heading',
            attrs: { level: 3 },
            content: [{ type: 'text', text: 'API Test Failure Details' }],
          },
          {
            type: 'paragraph',
            content: [
              { type: 'text', text: `Report: `, marks: [{ type: 'strong' }] },
              { type: 'text', text: reportName || 'Unknown' },
            ],
          },
          {
            type: 'paragraph',
            content: [
              { type: 'text', text: `Status: `, marks: [{ type: 'strong' }] },
              { type: 'text', text: `HTTP ${result.statusCode} ${result.statusText || ''} — ${result.latencyMs}ms` },
            ],
          },
          {
            type: 'heading',
            attrs: { level: 4 },
            content: [{ type: 'text', text: 'Request Payload Sent' }],
          },
          {
            type: 'codeBlock',
            attrs: { language: 'json' },
            content: [{ type: 'text', text: JSON.stringify(result.payloadBody, null, 2) }],
          },
          {
            type: 'heading',
            attrs: { level: 4 },
            content: [{ type: 'text', text: 'Response Received' }],
          },
          {
            type: 'codeBlock',
            attrs: { language: 'json' },
            content: [{ type: 'text', text: result.error ? result.error : JSON.stringify(result.response, null, 2) }],
          },
        ],
      };

      const response = await axios.post(
        `https://${host}/rest/api/3/issue`,
        {
          fields: {
            project: { key: project },
            summary: `[API Failure] ${result.payloadName} — HTTP ${result.statusCode}`,
            description,
            issuetype: { name: 'Bug' },
            labels: ['api-test-failure'],
          },
        },
        {
          headers: {
            Authorization: `Basic ${auth}`,
            'Content-Type': 'application/json',
          },
        }
      );

      created.push({
        issueKey: response.data.key,
        issueUrl: `https://${host}/browse/${response.data.key}`,
        payloadName: result.payloadName,
      });
    }

    res.json({ created, count: created.length });
  } catch (err) {
    if (err.response?.data) {
      return res.status(err.response.status || 500).json({
        error: 'Jira API error',
        details: err.response.data,
      });
    }
    next(err);
  }
};

/**
 * GET /api/bugs/config
 * Returns which integrations are configured (without exposing secrets)
 */
exports.getConfig = async (req, res) => {
  res.json({
    github: !!(process.env.GITHUB_TOKEN && process.env.GITHUB_OWNER && process.env.GITHUB_REPO),
    jira:   !!(process.env.JIRA_HOST && process.env.JIRA_EMAIL && process.env.JIRA_API_TOKEN && process.env.JIRA_PROJECT_KEY),
    githubRepo: process.env.GITHUB_OWNER && process.env.GITHUB_REPO
      ? `${process.env.GITHUB_OWNER}/${process.env.GITHUB_REPO}`
      : null,
    jiraProject: process.env.JIRA_PROJECT_KEY || null,
  });
};